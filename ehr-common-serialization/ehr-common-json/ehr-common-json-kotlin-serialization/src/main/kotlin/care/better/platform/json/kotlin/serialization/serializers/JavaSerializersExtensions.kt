import java.time.OffsetTime
import java.time.ZonedDateTime

/**
 * @author Primoz Delopst
 * @since 4.2.2
 *
 * Set of extension functions to register contextual serializers for various Java classes.
 */

internal fun SerializersModuleBuilder.registerAdditionalJavaSerializers() {
    contextual(BigDecimal::class, BigDecimalSerializer)
    contextual(BigInteger::class, BigIntegerSerializer)
    contextual(LocalDate::class, LocalDateSerializer)
    contextual(LocalTime::class, LocalTimeSerializer)
    contextual(LocalDateTime::class, LocalDateTimeSerializer)
    contextual(OffsetTime::class, OffsetTimeSerializer)
    contextual(OffsetDateTime::class, OffsetDateTimeSerializer)
    contextual(ZonedDateTime::class, ZonedDateTimeTimeSerializer)
    contextual(Instant::class, InstantSerializer)
}


internal object BigDecimalSerializer : KSerializer<BigDecimal> {
    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("BigDecimal", PrimitiveKind.STRING)

    override fun serialize(encoder: Encoder, value: BigDecimal) {
        encoder.encodeString(value.toString())
    }

    override fun deserialize(decoder: Decoder): BigDecimal = BigDecimal(decoder.decodeString())
}

